function detectLang(): 'uk' | 'en' {
  try {
    const code = getLocales()[0]?.languageCode ?? 'uk';
    // Ukrainian by default; English only on English-language devices.
    return code === 'en' ? 'en' : 'uk';
  } catch {
    return 'uk';
  }
}

export type LangChoice = 'auto' | 'uk' | 'en';

/** Current UI language. Changes when the user picks one in Settings (see setLang). */
export let lang: 'uk' | 'en' = detectLang();
let S: Strings = lang === 'en' ? en : uk;

/** Switch the UI language; 'auto' follows the phone. The caller re-renders the screen. */
export function setLang(choice: LangChoice): void {
  lang = choice === 'auto' ? detectLang() : choice;
  S = lang === 'en' ? en : uk;
}

export type StringKey = keyof Strings;

export function t(key: keyof Strings, vars: Record<string, string | number> = {}): string {
  return S[key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));
}

export const zoneName = (z: { name: string; nameEn?: string }) => (lang === 'en' && z.nameEn ? z.nameEn : z.name);

export function timeAgo(iso: string | null, now = Date.now()): string {
  if (!iso) return '';
  const min = Math.floor((now - Date.parse(iso)) / 60_000);
  if (min < 1) return t('justNow');
  if (min < 60) return t('minutesAgo', { n: min });
  const d = new Date(iso);
  return `${String(d.getHours()).padStart(2, '0')}:${String(d.getMinutes()).padStart(2, '0')}`;
}
